// Package compilerworker compiles and links C++ in an isolated temporary directory.
// It deliberately never executes the resulting program; this is not a sandbox.
package compilerworker

import (
	"context"
	"errors"
	"net/http"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"sync"
	"time"
	"unicode/utf8"

	"oj.local/oj/internal/compilation"
)

type Runner struct {
	CompilerPath string
	CompilerName string
	Timeout      time.Duration
	TempRoot     string
	busy         chan struct{}
	command      func(context.Context, string) *exec.Cmd
}

func New(path, name string) *Runner {
	return &Runner{CompilerPath: path, CompilerName: name, Timeout: 15 * time.Second, busy: make(chan struct{}, 1)}
}

func (r *Runner) Handler() http.Handler {
	mux := http.NewServeMux()
	mux.HandleFunc("GET /healthz", func(w http.ResponseWriter, _ *http.Request) {
		if _, err := os.Stat(r.CompilerPath); err != nil {
			compilation.WriteError(w, &compilation.Error{Status: 503, Code: "compiler_unavailable", Message: "编译器不可用。"})
			return
		}
		compilation.WriteJSON(w, 200, map[string]string{"status": "ok", "compiler": r.CompilerName})
	})
	mux.HandleFunc("POST /compile", func(w http.ResponseWriter, request *http.Request) {
		var body struct {
			Source string `json:"source"`
		}
		if err := compilation.Decode(w, request, &body); err != nil {
			compilation.WriteError(w, err)
			return
		}
		if err := compilation.ValidateSource(body.Source); err != nil {
			compilation.WriteError(w, err)
			return
		}
		result, err := r.Compile(request.Context(), body.Source)
		if err != nil {
			compilation.WriteError(w, err)
			return
		}
		compilation.WriteJSON(w, 200, result)
	})
	return mux
}

func (r *Runner) Compile(parent context.Context, source string) (compilation.Result, *compilation.Error) {
	select {
	case r.busy <- struct{}{}:
		defer func() { <-r.busy }()
	default:
		return compilation.Result{}, &compilation.Error{Status: 429, Code: "compiler_busy", Message: "编译服务繁忙，请稍后重试。"}
	}
	started := time.Now()
	dir, err := os.MkdirTemp(r.TempRoot, "oj-compile-")
	if err != nil {
		return compilation.Result{}, internalError()
	}
	// dir is generated by MkdirTemp, never derived from a user filename.
	defer os.RemoveAll(dir)
	if err := os.WriteFile(filepath.Join(dir, "solution.cpp"), []byte(source), 0600); err != nil {
		return compilation.Result{}, internalError()
	}
	ctx, cancel := context.WithTimeout(parent, r.Timeout)
	defer cancel()
	cmd := exec.CommandContext(ctx, r.CompilerPath, "-std=c++20", "-O0", "-fdiagnostics-color=never", "solution.cpp", "-o", "program")
	if r.command != nil {
		cmd = r.command(ctx, dir)
	}
	cmd.Dir = dir
	configureProcess(cmd)
	diagnostics := &boundedOutput{limit: compilation.MaxDiagnosticsBytes}
	cmd.Stdout, cmd.Stderr = diagnostics, diagnostics
	err = cmd.Run()
	result := compilation.Result{Status: "success", Diagnostics: diagnostics.text(), DiagnosticsTruncated: diagnostics.truncated, DurationMS: time.Since(started).Milliseconds(), Compiler: r.CompilerName, Standard: "c++20"}
	if ctx.Err() != nil {
		result.Status = "timeout"
		return result, nil
	}
	if err != nil {
		var exit *exec.ExitError
		if errors.As(err, &exit) {
			result.Status = "compile_error"
			return result, nil
		}
		return compilation.Result{}, internalError()
	}
	if info, err := os.Stat(filepath.Join(dir, "program")); err != nil || !info.Mode().IsRegular() {
		return compilation.Result{}, internalError()
	}
	return result, nil
}

func internalError() *compilation.Error {
	return &compilation.Error{Status: 502, Code: "compiler_failure", Message: "编译服务处理失败。"}
}

type boundedOutput struct {
	mu        sync.Mutex
	data      []byte
	limit     int
	truncated bool
}

func (b *boundedOutput) Write(p []byte) (int, error) {
	b.mu.Lock()
	defer b.mu.Unlock()
	n := len(p)
	remaining := b.limit - len(b.data)
	if len(p) > remaining {
		b.truncated = true
		p = p[:remaining]
	}
	b.data = append(b.data, p...)
	return n, nil // Continue draining the compiler after reaching the display limit.
}

func (b *boundedOutput) text() string {
	value := strings.ToValidUTF8(string(b.data), "?")
	if len(value) > b.limit {
		value = value[:b.limit]
	}
	for !utf8.ValidString(value) {
		value = value[:len(value)-1]
	}
	return value
}
